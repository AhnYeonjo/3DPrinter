"""Klipper config <-> Tool import/export.

import_tool_cfg():  read an existing T*.cfg and recover a Tool object so 3DOS can
                    adopt a printer that is already running klipper-toolchanger.
generate_tool_cfg(): emit a board-agnostic T*.cfg from a Tool object.
generate_toolchanger_cfg(): emit the shared toolchanger-config.cfg block.

The generator targets klipper-toolchanger-easy conventions so output drops into
~/printer_data/config/toolchanger/tools/ unchanged.
"""
from __future__ import annotations

import re
from .model import Tool, Extruder, Dock, Offsets, InputShaper, BOARD_PRESETS


# ---------- import ----------------------------------------------------------

def _f(text: str, key: str, default=None):
    m = re.search(rf"^\s*{re.escape(key)}\s*:\s*([-\d.]+)", text, re.M)
    return float(m.group(1)) if m else default


def import_tool_cfg(text: str, tool_number: int) -> Tool:
    uuid_m = re.search(r"canbus_uuid\s*:\s*([0-9a-fA-F]+)", text)
    alias_m = re.search(r"\[mcu\s+(\w+)\]", text)
    board = "EBB36" if re.search(r"\bPB13\b|\bPD0\b", text) else "SHT36"

    ext = Extruder(
        rotation_distance=_f(text, "rotation_distance", 47.088),
        pressure_advance=_f(text, "pressure_advance", 0.04),
        max_temp=int(_f(text, "max_temp", 300)),
    )
    gr = re.search(r"gear_ratio\s*:\s*([\d:]+)", text)
    if gr:
        ext.gear_ratio = gr.group(1)
    st = re.search(r"sensor_type\s*:\s*(.+)", text)
    if st:
        ext.sensor_type = st.group(1).strip()

    dock = Dock(
        park_x=_f(text, "params_park_x", 0.0),
        park_y=_f(text, "params_park_y", -11.0),
        park_z=_f(text, "params_park_z", 296.96),
    )
    off = Offsets(
        x=_f(text, "gcode_x_offset", 0.0),
        y=_f(text, "gcode_y_offset", 0.0),
        z=_f(text, "gcode_z_offset", 0.0),
    )
    shaper = InputShaper(
        freq_x=_f(text, "params_input_shaper_freq_x", 82.0),
        freq_y=_f(text, "params_input_shaper_freq_y", 61.8),
    )
    return Tool(
        tool_number=tool_number,
        name=f"T{tool_number}",
        board_type=board,
        canbus_uuid=uuid_m.group(1) if uuid_m else "",
        mcu_alias=alias_m.group(1) if alias_m else f"SHT{tool_number}",
        extruder=ext, dock=dock, offsets=off, shaper=shaper,
    )


# ---------- export ----------------------------------------------------------

def generate_tool_cfg(t: Tool) -> str:
    p = BOARD_PRESETS[t.board_type]["pins"]
    a = t.mcu_alias or f"SHT{t.tool_number}"
    pin = lambda k: f"{a}:{p[k]}"
    off = ""
    if any([t.offsets.x, t.offsets.y, t.offsets.z]):
        off = (f"gcode_x_offset: {t.offsets.x}\n"
               f"gcode_y_offset: {t.offsets.y}\n"
               f"gcode_z_offset: {t.offsets.z}\n")
    accel = ""
    if BOARD_PRESETS[t.board_type]["has_accel"]:
        accel = f"\n[lis2dw {t.name}_accel]\ncs_pin: {pin('accel_cs')}\n"

    return f"""#####################################################################
#  Tool {t.tool_number} - {BOARD_PRESETS[t.board_type]['label']}
#  Generated by 3DOS
#####################################################################

[mcu {a}]
canbus_uuid: {t.canbus_uuid}

[extruder{'' if t.tool_number == 0 else t.tool_number}]
step_pin: {pin('extruder_step')}
dir_pin: {pin('extruder_dir')}
enable_pin: !{pin('extruder_enable')}
rotation_distance: {t.extruder.rotation_distance}
gear_ratio: {t.extruder.gear_ratio}
microsteps: {t.extruder.microsteps}
full_steps_per_rotation: {t.extruder.full_steps_per_rotation}
nozzle_diameter: {t.extruder.nozzle_diameter}
filament_diameter: {t.extruder.filament_diameter}
heater_pin: {pin('heater')}
sensor_type: {t.extruder.sensor_type}
sensor_pin: {pin('thermistor')}
min_temp: 0
max_temp: {t.extruder.max_temp}
min_extrude_temp: {t.extruder.min_extrude_temp}
pressure_advance: {t.extruder.pressure_advance}

[tmc2209 extruder{'' if t.tool_number == 0 else t.tool_number}]
uart_pin: {pin('extruder_uart')}
run_current: {t.extruder.run_current}
sense_resistor: 0.110
stealthchop_threshold: 0

[tool_probe {t.name}]
pin: ^{pin('probe')}
tool: {t.tool_number}
z_offset: 0
speed: 8
samples: 3
samples_result: median
activate_gcode:
    _TAP_PROBE_ACTIVATE HEATER=extruder{'' if t.tool_number == 0 else t.tool_number}

[heater_fan {t.name}_hotend_fan]
pin: {pin('hotend_fan')}
heater: extruder{'' if t.tool_number == 0 else t.tool_number}
heater_temp: 50.0

[fan_generic {t.name}_part_fan]
pin: {pin('part_fan')}
max_power: 1.0
{accel}
[gcode_macro {t.name}]
gcode:
    {{% if printer.toolchanger.tool_number|default(-1)|int == {t.tool_number} %}}
        RESPOND MSG="{t.name} already mounted — skip"
    {{% else %}}
        SELECT_TOOL T={t.tool_number}
    {{% endif %}}

[tool {t.name}]
tool_number: {t.tool_number}
extruder: extruder{'' if t.tool_number == 0 else t.tool_number}
fan: {t.name}_part_fan
{off}params_park_x: {t.dock.park_x}
params_park_y: {t.dock.park_y}
params_park_z: {t.dock.park_z}
params_input_shaper_type_x: '{t.shaper.type_x}'
params_input_shaper_freq_x: {t.shaper.freq_x}
params_input_shaper_type_y: '{t.shaper.type_y}'
params_input_shaper_freq_y: {t.shaper.freq_y}
"""


def generate_toolchanger_cfg(tools: list[Tool]) -> str:
    d = tools[0].dock if tools else Dock()
    return f"""#####################################################################
#  toolchanger-config.cfg — generated by 3DOS
#  StealthChanger shared dock motion parameters
#####################################################################

[force_move]
enable_force_move: True

[toolchanger]
params_dropoff_path: {d.dropoff_path}
params_pickup_path: {d.pickup_path}
params_safe_y: {d.safe_y}
params_close_y: {d.close_y}
params_fast_speed: {d.fast_speed}
params_path_speed: {d.path_speed}
require_tool_present: False
"""
